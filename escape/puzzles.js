/* ジャンル名をタイトルの先頭に付ける（既存お題はここで割り当て） */
const OLD_CAT = {
  seq1:'数列', fib:'数列', abc:'暗号', liar:'論理', clock90:'時計', riddle:'なぞなぞ', palin:'言葉',
  magic:'数のパズル', week:'カレンダー', tsuru:'算数', square:'図形', shift:'暗号',
  jwk1:'簿記', jwk2:'簿記', equity:'簿記', digit:'数のパズル', divisor:'算数', mirror:'時計', sum10:'計算'
};
PUZZLES.forEach(p => { const c = p.cat || OLD_CAT[p.id]; if (c) p.title = '【' + c + '】' + p.title; });

function checkAnswer(p, input){
  if (p.type === 'choice') return Number(input) === p.correct;
  const v = norm(input);
  if (!v) return false;
  return p.answers.some(a => norm(a) === v);
}
